import { beforeEach, describe, expect, it } from 'vitest'
import { getTrace } from './library'
import { useLearning } from './store'
const state = () => useLearning.getState()
beforeEach(() => {
  state().load(getTrace('aliasing'))
  useLearning.setState({ predict: false, roots: false, theme: 'dark' })
})
describe('prediction gates', () => {
  it('blocks skipping a question via the scrubber or last-step action', () => {
    state().setPredict()
    state().seek(9)
    expect(state().index).toBe(3)
    expect(state().pending).toBe(4)
    state().setPlaying(true)
    expect(state().playing).toBe(false)
    state().next()
    expect(state().index).toBe(3)
    state().answer(0)
    expect(state().pending).toBe(4)
    expect(state().feedback).toContain('one Person')
    state().answer(1)
    expect(state().index).toBe(4)
    expect(state().pending).toBeNull()
    expect(state().answered['alias-name']).toBe(false)
    state().seek(9)
    expect(state().pending).toBe(7)
    expect(state().index).toBe(6)
  })
  it('records first-attempt scores once and allows backward review', () => {
    state().setPredict()
    state().seek(4)
    state().answer(1)
    expect(state().answered['alias-name']).toBe(true)
    state().previous()
    state().next()
    expect(state().pending).toBeNull()
    expect(Object.keys(state().answered)).toHaveLength(1)
  })
  it('stops playback and seeking when source no longer matches the trace', () => {
    state().edit('class Main {}')
    state().seek(5)
    state().setPlaying(true)
    expect(state().index).toBe(0)
    expect(state().playing).toBe(false)
    state().edit(state().trace.code)
    state().next()
    expect(state().index).toBe(1)
  })
})
